#!/usr/bin/env python
"""
make_tables.py -- LaTeX result tables for the paper, from summary/summary.json.

    python make_tables.py --summary $RESULTS_DIR/summary/summary.json --out <paper>/results
    python make_tables.py --placeholder --out <paper>/results      # empty tables ("--")
Also writes tab_settings_auto.tex from configs/experiment.yaml (the appendix settings table),
so the paper always shows the settings that were actually run.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import load_cfg, load_json  # noqa: E402

DASH = "--"
NICE = {"girder": "Girder", "deck": "Deck", "pier": "Pier", "main_cable": "Main cable", "suspender": "Suspender",
        "stay": "Stay", "pointnet": "PointNet", "pointnet2": "PointNet++", "true": "true classes",
        "vggt": "VGGT", "3dgs": "3DGS", "2dgs_mean": "2DGS mean"}


def f(v, mult=1.0, nd=1, pct=False):
    if v is None:
        return DASH
    try:
        x = float(v) * mult
    except (TypeError, ValueError):
        return DASH
    if x != x:
        return DASH
    txt = f"{x:.{nd}f}"
    if txt.startswith("-"):
        txt = "$-$" + txt[1:]  # a minus sign, not a hyphen, in text mode
    return txt + (r"\%" if pct else "")


def table(caption, label, colspec, header, rows, note=None):
    body = "\n".join("    " + " & ".join(r) + r" \\" for r in rows)
    note_tex = f"\n  \\par\\smallskip{{\\footnotesize {note}}}" if note else ""
    return (f"% generated by make_tables.py -- do not edit by hand\n\\begin{{table}}[t]\n  \\caption{{{caption}}}\n"
            f"  \\label{{{label}}}\n  \\centering\n  \\footnotesize\n  \\setlength{{\\tabcolsep}}{{4pt}}\n"
            f"  \\begin{{tabular}}{{{colspec}}}\n    \\toprule\n    {' & '.join(header)} \\\\\n    \\midrule\n"
            f"{body}\n    \\bottomrule\n  \\end{{tabular}}{note_tex}\n\\end{{table}}\n")


def semantic(S, classes, models):
    rows = []
    for m in models:
        d = (S or {}).get("semseg", {}).get(m, {})
        real, var = d.get("real", {}), d.get("variant", {})
        iou = real.get("iou") or [None] * len(classes)
        rows.append([NICE.get(m, m)] + [f(v, 100) for v in iou] + [f(real.get("miou"), 100), f(var.get("miou"), 100)])
    return table("Semantic segmentation on BrPCD, pooled over the test bridges of all folds (IoU in \\%). Headline "
                 "columns use the real scans; the last column uses the augmented variants as an upper reference.",
                 "tab:res-semantic", "@{}l" + "r" * (len(classes) + 2) + "@{}",
                 ["Model"] + [NICE[c] for c in classes] + ["mIoU real", "mIoU var."], rows)


def semseg_perbridge(S, models, cfg):
    r"""Per-bridge mIoU over girder/deck/pier, next to the BrPCD paper's own table.

    The paper (Table 4) reports one mIoU per bridge, not a pooled mean, so this is the only
    honest side-by-side. Bridges the paper does not tabulate are still shown, with "--" for
    their reference value; the mean row averages every real bridge for every column.
    """
    ref = cfg.get("ref_semseg") or {}
    paper = ref.get("values") or {}
    per = {m: ((S or {}).get("semseg", {}).get(m, {}) or {}).get("per_bridge") or {} for m in models}
    bridges = sorted({b for m in models for b in per[m]})
    header = ["Bridge", "cls", "Paper"] + sum([[NICE.get(m, m), r"$\Delta$"] for m in models], [])
    colspec = "@{}l" + "r" * (2 * len(models) + 2) + "@{}"
    caption = r"Per-bridge semantic segmentation on BrPCD: mIoU over girder, deck and pier (\%)."
    if not bridges:
        return table(caption, "tab:res-semseg-bridge", colspec, header,
                     [["(no run yet)", DASH, DASH] + [DASH] * (2 * len(models))],
                     note="--summary was not given, or no fold has per-cloud metrics yet.")

    rows, sums = [], {m: [] for m in models}
    for b in bridges:
        cls_n = max((per[m].get(b) or {}).get("n_cls", 0) for m in models)
        row = [b, str(cls_n) if cls_n else DASH, f(paper.get(b), 1, 3)]
        for m in models:
            v = (per[m].get(b) or {}).get("miou")
            sums[m].append(v)
            d = (v - paper[b]) if (v is not None and b in paper) else None
            row += [f(v, 1, 3), f(d, 1, 3)]
        rows.append(row)

    def mean_of(xs):
        xs = [x for x in xs if x is not None]
        return sum(xs) / len(xs) if xs else None

    rows.append(["mean", "", DASH] + sum([[f(mean_of(sums[m]), 1, 3), ""] for m in models], []))
    n_ref = sum(1 for b in bridges if b in paper)
    note = (f"The paper's column is {ref.get('source', 'the BrPCD paper')}, over the classes each bridge "
            f"labels. It covers {n_ref} of the {len(bridges)} real bridges here; the mean row averages all "
            f"{len(bridges)} for every column, so it is not the paper's mean. Delta = ours minus paper. Our "
            f"folds withhold the entire bridge while the reference trains on the complete databank, so a "
            f"match is a reproduction under a stricter protocol, and a large negative is a real failure.")
    return table(caption, "tab:res-semseg-bridge", colspec, header, rows, note=note)


def instances(S, sources):
    rows = []
    I = (S or {}).get("instances", {})
    for src in sources:
        for meth in ("M1", "M2"):
            d = I.get(src, {}).get(meth, {})
            h1 = I.get(src, {}).get("H1", {}) or {}
            h = (h1.get("all") or {}) if meth == "M2" else {}
            ci = f"[{f(h.get('lo'), 100)}, {f(h.get('hi'), 100)}]" if h else ""
            rows.append([NICE.get(src, src) if meth == "M1" else "", meth,
                         f(d.get("real", {}).get("PQ"), 100), f(d.get("real", {}).get("SQ"), 100),
                         f(d.get("real", {}).get("RQ"), 100), f(d.get("variant", {}).get("PQ"), 100),
                         f(d.get("slope_all"), 100), (f(h.get("diff"), 100) + " " + ci) if h else ""])
    # failed fits are excluded from every M2 number above: say so in the table, not only in the log
    nf = sum(int((I.get(s, {}).get("M2", {}) or {}).get("n_failed") or 0) for s in sources)
    nd = sum(int(((I.get(s, {}).get("H1") or {}).get("n_dropped")) or 0) for s in sources)
    note = (f"M2 layout fits that raised an error are excluded rather than scored as zero "
            f"({nf} cloud(s) failed, {nd} bridge pairing(s) dropped from $\\Delta\\beta_1$).") if (nf or nd) else None
    return table("Member instances on BrPCD (\\%). PQ, SQ and RQ on the real test scans; PQ on the variants; "
                 "$\\beta_1$ is the slope of PQ against $\\log N$ (\\cref{eq:trend}) and $\\Delta\\beta_1$ = slope(M2) "
                 "$-$ slope(M1) with its 95\\% bridge-level bootstrap interval (H1 expects it to be positive).",
                 "tab:res-instances", "@{}llrrrrrl@{}",
                 ["Classes from", "Method", "PQ", "SQ", "RQ", "PQ var.", "$\\beta_1$", "$\\Delta\\beta_1$ [95\\% CI]"], rows,
                 note=note)


def render(S):
    R = ((S or {}).get("trackB") or {}).get("render", {})
    rows = []
    for key, name in (("gs3d", "3DGS"), ("gs2d", "2DGS")):
        d = R.get(key, {})
        m = d.get("metrics_images", {}).get("mean", {})
        info = d.get("run_info", {})
        rows.append([name, f(m.get("psnr"), 1, 2), f(m.get("ssim"), 1, 3), f(m.get("lpips"), 1, 3),
                     f(info.get("train_seconds"), 1 / 60, 0), f(info.get("n_gaussians"), 1e-6, 2)])
    return table("Rendering on the held-out VTTI views (every 8th image). Training time in minutes and the final "
                 "number of Gaussians in millions.", "tab:res-render", "@{}lrrrrr@{}",
                 ["Method", "PSNR (dB)", "SSIM", "LPIPS", "Time (min)", "Gaussians (M)"], rows)


def measure(S, spans_ref):
    M = ((S or {}).get("trackB") or {}).get("measure", {})
    rows = [["Reference", DASH, f(spans_ref[0], 1, 3), f(spans_ref[1], 1, 3), f(spans_ref[2], 1, 3), DASH, DASH, DASH]]
    keys = [k for k in ("3dgs", "2dgs", "2dgs_mean") if k in M] + sorted(k for k in M if k not in ("3dgs", "2dgs", "2dgs_mean"))
    for key in keys or ["3dgs", "2dgs"]:
        d = M.get(key, {})
        sp = d.get("spans_m") or [None] * 3
        er = d.get("rel_err") or [None] * 3
        rms = (d.get("deck_rms_m") or {}).get("median")
        rows.append([d.get("label", key.upper()), f(d.get("kappa"), 1, 4), f(sp[0], 1, 3), f(sp[1], 1, 3), f(sp[2], 1, 3),
                     f(er[0], 100, 2, True), f(er[2], 100, 2, True), f(rms, 1000, 1)])
    return table("Metric checks on VTTI. The scale $\\kappa$ fixes the 150\\,ft main span ($L_2$, exact by construction); "
                 "the 90\\,ft side spans $L_1$ and $L_3$ are the check (target error 2\\%). Deck residual = median "
                 "plane-fit RMS over 2\\,m patches, in mm.", "tab:res-measure", "@{}lrrrrrrr@{}",
                 ["Method", "$\\kappa$", "$L_1$ (m)", "$L_2$ (m)", "$L_3$ (m)", "$e_1$", "$e_3$", "Deck RMS"], rows)


def _spacing(m2):
    gs = m2.get("girder_spacing_m") or []
    lo, hi = (f(min(gs), 1, 2), f(max(gs), 1, 2)) if gs else (DASH, DASH)
    return lo if lo == hi else f"{lo} to {hi}"


def rq3(S):
    R = (S or {}).get("rq3") or {}
    extra = (S or {}).get("rq3_extra") or {}          # optional repeats on other point clouds (M2 only)
    ref, m1, m2 = R.get("reference", {}), R.get("M1", {}), R.get("M2", {})
    sp_ref = ref.get("spans_m") or [None] * 3
    sp2 = m2.get("spans_m") or [None] * 3
    ex = [(NICE.get(k, k.upper()), (v.get("M2") or {})) for k, v in sorted(extra.items())]
    rows = [["Girders", str(ref.get("girders")) if ref.get("girders") is not None else DASH,
             str(m1.get("girders", DASH)), str(m2.get("girders", DASH))] + [str(e.get("girders", DASH)) for _, e in ex],
            ["Piers", str(ref.get("piers", DASH)), str(m1.get("piers", DASH)), str(m2.get("piers", DASH))]
            + [str(e.get("piers", DASH)) for _, e in ex]]
    for k in range(3):
        rows.append([f"$L_{k + 1}$ (m)", f(sp_ref[k], 1, 2), DASH, f(sp2[k], 1, 2)]
                    + [f((e.get("spans_m") or [None] * 3)[k], 1, 2) for _, e in ex])
    rows.append(["Girder spacing (m)", DASH, DASH, _spacing(m2)] + [_spacing(e) for _, e in ex])
    cap = ("RQ3: members and spans recovered from the 2DGS points of VTTI. Reference counts are taken from the "
           "photographs, reference spans from the dataset description.")
    if ex:
        cap += " The last column" + ("s repeat" if len(ex) > 1 else " repeats") + " M2 on the " + \
               ", ".join(n for n, _ in ex) + " points."
    return table(cap, "tab:res-rq3", "@{}lrrr" + "r" * len(ex) + "@{}",
                 ["Quantity", "Reference", "M1", "M2"] + [f"M2 ({n})" for n, _ in ex], rows)


def settings(cfg):
    b, s, m1, m2, v, g3, g2, pt, ms, mg = (cfg[k] for k in ("brpcd", "semseg", "m1", "m2", "vtti", "gs3d", "gs2d",
                                                           "points", "measure", "merge"))
    vg = cfg.get("vggt") or {"enabled": False}
    tune = m2.get("tune") or {}
    lst = lambda x: ", ".join(str(i) for i in x)
    vox = "2$\\times$ median spacing of the real scans" if b["voxel_size"] == "auto" else f"{b['voxel_size']} m"
    split_txt = {"loo": "leave one bridge out", "fixed3": "one fixed test scan per bridge type"}.get(
        cfg["splits"]["mode"], cfg["splits"]["mode"])
    rows = [
        ("BrPCD", f"voxel {vox} (clipped to {b['voxel_size_min']} to {b['voxel_size_max']} m); normals from {b['normals_k']} "
                  f"neighbours; members under {b['min_instance_points']} points dropped"),
        ("Splits", f"{split_txt} over the real scans, variants follow their scan; "
                   f"{cfg['splits']['val_per_fold']} validation scan per fold"),
        ("Semantic nets", f"{', '.join(NICE[x] for x in s['models'])}; {s['block_size']:.0f} m blocks of {s['block_points']} points, "
                          f"batch {s['batch_size']}, {s['iterations']:,} iterations, AdamW lr {s['lr']}, weight decay "
                          f"{s['weight_decay']}, class weights $n_c^{{-{s['class_weight_power']}}}$"),
        ("M1", f"$\\varepsilon \\in \\{{{lst(m1['eps_grid'])}\\}}$ m, $m_{{\\mathrm{{pts}}}} \\in \\{{{lst(m1['min_pts_grid'])}\\}}$, per class"),
        ("M2", f"$\\delta$ {m2['deck_ransac_thresh']} m; $b_s \\in \\{{{lst(tune.get('kde_bw_station', [m2['kde_bw_station']]))}\\}}$, "
               f"$b_t \\in \\{{{lst(tune.get('kde_bw_offset', [m2['kde_bw_offset']]))}\\}}$, "
               f"$\\eta \\in \\{{{lst(tune.get('peak_eta', [m2['peak_eta']]))}\\}}$, "
               f"$\\delta_c \\in \\{{{lst(tune.get('cable_thresh', [m2['cable_thresh']]))}\\}}$ m; $m_{{\\min}}$ {m2['cable_min_inliers']}; "
               f"box-girder valley {m2.get('offset_valley_frac')}"),
        ("Metrics", f"PQ match IoU $>$ {cfg['metrics']['pq_iou']}; segments under {cfg['metrics']['min_segment_points']} points "
                    f"are noise; {cfg['metrics']['bootstrap']} bootstrap resamples of whole bridges"),
        ("VTTI images", f"COLMAP project {v['model']}; undistorted, long side {v['long_side_px']} px; every {v['test_every']}th image held out"),
        ("3DGS", f"{g3['iterations']:,} iterations, $\\lambda$ {g3['lambda_dssim']}, densification gradient {g3['densify_grad_threshold']} "
                 f"until {g3['densify_until_iter']:,}"),
        ("2DGS", f"{g2['iterations']:,} iterations, $\\lambda_d$ {g2['lambda_dist']:g}, $\\lambda_n$ {g2['lambda_normal']}; TSDF voxel "
                 f"{g2['tsdf_voxel_m']} m, truncation {g2['sdf_trunc_voxels']} voxels, depth cut {g2['depth_trunc_m']:g} m; "
                 f"depth ratio {lst(g2['mesh_depth_ratios'])} (median, expected)"),
        ("Point clouds", f"3DGS centres with opacity $>$ {pt['gs3d_min_opacity']}; {pt['mesh_samples']:,} area samples of the 2DGS mesh"),
    ] + ([
        ("VGGT", f"VGGT-1B, one pass on at most {vg['max_frames']} images (width 518 px), no camera input; depth unprojected with "
                 f"the predicted cameras, confidence above the {vg['conf_percentile']}th percentile, {vg['max_points']:,} points; "
                 f"similarity fit to the COLMAP camera centres"),
    ] if vg.get("enabled", True) else []) + [
        ("Measurement", f"deck plane within {ms['deck_normal_max_deg']:g}\\textdegree{{}} of the camera vertical; girder band "
                        f"${ms['girder_band_m'][0]:g}$ to ${ms['girder_band_m'][1]:g}$ m; pier crops below ${-ms['pier_below_deck_m']:g}$ m; "
                        f"station = midpoint of the {ms['station_pct'][0]}th and {ms['station_pct'][1]}th percentiles; "
                        f"{ms['deck_patch_m']:g} m deck patches"),
        ("RQ3", f"{NICE[mg['semseg_model']]} trained on every BrPCD cloud; crop margin {mg['crop_margin_m']:g} m"),
    ]
    body = "\n".join(f"    {a} & {b_} \\\\" for a, b_ in rows)
    return ("% generated by make_tables.py from configs/experiment.yaml -- do not edit by hand\n"
            "\\begin{table}[t]\n  \\caption{Settings used for every run, generated from \\texttt{configs/experiment.yaml}. "
            "Grids in braces are searched on the validation bridges of each fold.}\n  \\label{tab:settings}\n"
            "  \\centering\n  \\footnotesize\n  \\setlength{\\tabcolsep}{4pt}\n  \\renewcommand{\\arraystretch}{1.1}\n"
            "  \\begin{tabularx}{\\linewidth}{@{}>{\\raggedright\\arraybackslash}p{2.1cm} "
            ">{\\raggedright\\arraybackslash}X@{}}\n    \\toprule\n    Stage & Setting \\\\\n    \\midrule\n"
            f"{body}\n    \\bottomrule\n  \\end{{tabularx}}\n\\end{{table}}\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", default=None)
    ap.add_argument("--out", required=True)
    ap.add_argument("--cfg", default=None)
    ap.add_argument("--placeholder", action="store_true")
    a = ap.parse_args()
    cfg = load_cfg(a.cfg)
    S = None if a.placeholder or not a.summary else load_json(a.summary)
    os.makedirs(a.out, exist_ok=True)
    classes = cfg["brpcd"]["classes"]
    models = cfg["semseg"]["models"]
    sources = [m for m in models] + ["true"]
    spans_ref = [x * 0.3048 for x in cfg["vtti"]["spans_ft"]]
    files = {"res_semantic.tex": semantic(S, classes, models),
             "res_semseg_perbridge.tex": semseg_perbridge(S, models, cfg),
             "res_instances.tex": instances(S, sources),
             "res_render.tex": render(S), "res_measure.tex": measure(S, spans_ref), "res_rq3.tex": rq3(S),
             "tab_settings_auto.tex": settings(cfg)}
    for name, tex in files.items():
        with open(os.path.join(a.out, name), "w") as fh:
            fh.write(tex)
    print(f"tables written to {a.out}: {', '.join(files)}")


if __name__ == "__main__":
    main()
